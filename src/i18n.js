  function normalize(text) {
    return String(text).replace(/\s+/g, " ").trim();
  }

  function getBn(text) {
    var key = normalize(text);
    return dictionary.hasOwnProperty(key) ? dictionary[key] : text;
  }

  function currentLang() {
    try {
      var lang = localStorage.getItem(LANG_KEY);
      return lang === "bn" || lang === "en" ? lang : DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;
    }
  }

  function setLang(lang) {
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch (e) {
      /* storage unavailable */
    }
  }

  var titleOriginal = "";
  var capturedText = []; // { node, original }
  var capturedAttrs = []; // { el, attr, original }

  function captureNodes() {
    titleOriginal = document.title;

    capturedText = [];
    if (document.body) {
      var walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
          acceptNode: function (node) {
            var parent = node.parentElement;
            if (!parent) return NodeFilter.FILTER_REJECT;
            var tag = parent.tagName.toLowerCase();
            if (
              tag === "script" ||
              tag === "style" ||
              tag === "noscript" ||
              tag === "textarea"
            ) {
              return NodeFilter.FILTER_REJECT;
            }
            var txt = normalize(node.nodeValue);
            if (!txt) return NodeFilter.FILTER_REJECT;
            if (dictionary.hasOwnProperty(txt)) return NodeFilter.FILTER_ACCEPT;
            return NodeFilter.FILTER_REJECT;
          }
        }
      );
      var node;
      while ((node = walker.nextNode())) {
        capturedText.push({ node: node, original: node.nodeValue });
      }
    }

    capturedAttrs = [];
    var cases = [
      { sel: "input[placeholder]", attr: "placeholder" },
      { sel: "textarea[placeholder]", attr: "placeholder" },
      { sel: "[title]:not(.slumlink-lang-switch *)", attr: "title" },
      { sel: "img[alt]", attr: "alt" },
      { sel: "[aria-label]:not(.slumlink-lang-switch *)", attr: "aria-label" }
    ];
    for (var c = 0; c < cases.length; c++) {
      var els = document.querySelectorAll(cases[c].sel);
      for (var i = 0; i < els.length; i++) {
        var val = els[i].getAttribute(cases[c].attr);
        if (val && dictionary.hasOwnProperty(normalize(val))) {
          capturedAttrs.push({ el: els[i], attr: cases[c].attr, original: val });
        }
      }
    }
  }

  function applyLang(lang) {
    document.documentElement.setAttribute("lang", lang);
    if (document.body) document.body.setAttribute("data-lang", lang);

    if (lang === DEFAULT_LANG) {
      document.title = titleOriginal;
      for (var i = 0; i < capturedText.length; i++) {
        capturedText[i].node.nodeValue = capturedText[i].original;
      }
      for (var j = 0; j < capturedAttrs.length; j++) {
        capturedAttrs[j].el.setAttribute(capturedAttrs[j].attr, capturedAttrs[j].original);
      }
    } else {
      document.title = getBn(titleOriginal);
      for (var m = 0; m < capturedText.length; m++) {
        var original = capturedText[m].original;
        var key = normalize(original);
        if (!key || !dictionary.hasOwnProperty(key)) continue;
        var trimmed = original.match(/^(\s*)([\s\S]*?)(\s*)$/);
        capturedText[m].node.nodeValue =
          trimmed[1] + dictionary[key] + trimmed[3];
      }
      for (var n = 0; n < capturedAttrs.length; n++) {
        var aOriginal = capturedAttrs[n].original;
        capturedAttrs[n].el.setAttribute(
          capturedAttrs[n].attr,
          getBn(aOriginal)
        );
      }
    }

    var langBtns = document.querySelectorAll("[data-lang]");
    for (var k = 0; k < langBtns.length; k++) {
      var btnLang = langBtns[k].getAttribute("data-lang");
      var isActive = btnLang === lang;
      langBtns[k].classList.toggle("slumlink-active", isActive);
      langBtns[k].setAttribute("aria-pressed", isActive ? "true" : "false");
    }
  }

