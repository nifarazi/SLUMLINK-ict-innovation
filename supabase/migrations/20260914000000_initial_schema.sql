create or replace function public.assign_slum_code()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.slum_code is null then
    new.slum_code := 'SR' || lpad(new.id::text, 6, '0');
  end if;
  return new;
end;
$$;

create trigger assign_slum_code_before_insert
before insert on public.slum_dwellers
for each row execute function public.assign_slum_code();

create trigger set_slum_dwellers_updated_at
before update on public.slum_dwellers
for each row execute function public.set_updated_at();

