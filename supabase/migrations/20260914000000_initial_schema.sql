-- SLUMLINK compatibility-first migration from MySQL to Supabase PostgreSQL.
--
-- This migration intentionally preserves the current table and column names so
-- the Express API can be migrated incrementally. Binary columns remain bytea
-- for now; a later migration will move files to Supabase Storage.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.organizations (
  org_id bigint generated by default as identity (start with 2000) primary key,
  org_type text not null default 'ngo'
    check (org_type in ('ngo', 'localauthority')),
  org_name varchar(150) not null,
  email varchar(150) not null unique,
  phone varchar(20) not null unique,
  org_age integer not null check (org_age >= 0),
  password varchar(255) not null,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected', 'suspended')),
  license_filename varchar(255) not null,
  license_mimetype varchar(100) not null,
  license_size bigint not null check (license_size >= 0),
  license_file bytea not null
);

create table public.slum_dwellers (
