create or replace function public.assign_distribution_round()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.round_no is null or new.round_no <= 0 then
    select coalesce(max(de.round_no), 0) + 1
      into new.round_no
      from public.distribution_entries as de
     where de.session_id = new.session_id
       and de.family_code = new.family_code;
  end if;
  return new;
end;
$$;

create trigger assign_distribution_round_before_insert
before insert on public.distribution_entries
for each row execute function public.assign_distribution_round();

